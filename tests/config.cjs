'use strict';
const assert = require('node:assert/strict');
const { normalize, phone, https, embed } = require('../scripts/config.cjs');
assert.equal(phone('(11) 99999-9999'), '5511999999999');
assert.equal(phone('55 11 99999-9999'), '5511999999999');
assert.equal(phone('+55 (11) 99999-9999'), '5511999999999');
assert.equal(phone('0055 11 99999-9999'), '5511999999999');
assert.equal(phone('(55) 99999-9999'), '5555999999999');
assert.equal(phone('+44 20 1234 5678'), '442012345678');
for (const value of ['', 'abc', '123', '+55 11 999', '++55 11 99999-9999', '0'.repeat(16)]) assert.equal(phone(value), '');
for (const value of ['http://example.com', 'javascript:alert(1)', '//example.com', 'https:example.com', 'https://user:pass@example.com', 'https://exa mple.com']) assert.equal(https(value), '');
assert.equal(https('https://example.com/path'), 'https://example.com/path');
for (const value of ['https://www.google.com.evil.test/maps/embed', 'https://evil.test/map', 'http://www.google.com/maps/embed', 'https://www.google.com/maps/search', 'https://www.google.com:8443/maps/embed']) assert.equal(embed(value), '');
assert.ok(embed('https://www.google.com/maps/embed?pb=test'));
assert.ok(embed('https://www.openstreetmap.org/export/embed.html?bbox=0,0,1,1'));
const warnings = [];
const bad = normalize({ whatsapp:'secret-invalid-value', services:[null,{}, { name:'Serviço',price:-2 }], reviews:{verified:true,average:6}, mapa:{embed:'https://evil.test'} }, m=>warnings.push(m));
assert.equal(bad.whatsapp,'');
assert.equal(bad.services.length,1);
assert.equal(bad.services[0].price,null);
assert.equal(bad.reviews.active,false);
assert.equal(bad.mapa.embed,'');
assert.ok(warnings.length>0);
assert.ok(warnings.every(m=>!m.includes('secret-invalid-value')));
for (const value of [undefined,null,{}, {demo:{enabled:false}}]) assert.doesNotThrow(()=>normalize(value,()=>{}));
for (const average of [0,4,4.5,4.7,5]) assert.equal(normalize({reviews:{verified:true,average}},()=>{}).reviews.active,true);
assert.equal(normalize({reviews:{verified:false,average:4.5,count:20}},()=>{}).reviews.active,false);
console.log('PASS config: BR/international phones, HTTPS, trusted map origins, safe defaults, review boundaries and private warning values');

const photo = src => ({src,alt:'Fixture de teste de configuração'});
const gallery = normalize({images:{gallery:[photo('assets/one.jpg'),photo('assets/one.jpg'),photo('assets/two.jpg'),photo('assets/three.jpg'),photo('assets/four.jpg'),photo('assets/five.jpg')]}},()=>{}).images.gallery;
assert.deepEqual(gallery.map(item=>item.src),['assets/one.jpg','assets/two.jpg','assets/three.jpg','assets/four.jpg']);
assert.equal(normalize({},()=>{}).whatsappUnavailableMessage,'WhatsApp disponível em breve');
assert.equal(normalize({whatsappUnavailableMessage:'Mensagem própria'},()=>{}).whatsappUnavailableMessage,'Mensagem própria');
console.log('PASS gallery: até quatro referências distintas; aviso sem número configurável');

const {brandIcon}=require('../scripts/brand-icon.cjs');
assert.ok(!brandIcon('B').includes('<text'),'B vetorial sem fonte externa');
assert.ok(brandIcon('B').includes('fill-rule="evenodd"'));
console.log('PASS favicon: monograma B vetorial independente de fontes');
